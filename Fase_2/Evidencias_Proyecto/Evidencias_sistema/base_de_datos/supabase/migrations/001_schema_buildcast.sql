-- 12. RPC de plantillas y partidas del proyecto

-- Reemplaza la lista completa de una plantilla (agregar, quitar, ordenar). Solo service role.
create or replace function public.guardar_partidas_plantilla(
    p_plantilla_id uuid,
    p_partidas jsonb
)
returns setof public.plantilla_partidas
language plpgsql
set search_path = ''
as $$
begin
    perform 1 from public.plantillas_presupuesto where id = p_plantilla_id for update;
    if not found then
        raise exception 'La plantilla no existe.'
            using errcode = 'P0002';
    end if;

    if jsonb_typeof(p_partidas) is distinct from 'array' then
        raise exception 'Las partidas de la plantilla deben ser una lista.'
            using errcode = '22023';
    end if;

    if exists (
        select 1
        from jsonb_populate_recordset(null::public.plantilla_partidas, p_partidas) r
        left join public.partidas p on p.id = r.partida_id
        where p.id is null or not p.vigente
    ) then
        raise exception 'Alguna partida no existe o está dada de baja.'
            using errcode = '22023';
    end if;

    delete from public.plantilla_partidas where plantilla_id = p_plantilla_id;

    -- Duplicados: el unique (plantilla_id, partida_id) lanza 23505.
    insert into public.plantilla_partidas (plantilla_id, partida_id, orden, cantidad_sugerida)
    select p_plantilla_id, r.partida_id, r.orden, r.cantidad_sugerida
    from jsonb_populate_recordset(null::public.plantilla_partidas, p_partidas) r;

    update public.plantillas_presupuesto
    set fecha_actualizacion = now()
    where id = p_plantilla_id;

    return query
        select * from public.plantilla_partidas
        where plantilla_id = p_plantilla_id
        order by orden;
end;
$$;

-- Copia una plantilla a un proyecto. Corre con los permisos del usuario (RLS);
-- las filas ya vienen armadas desde el backend. Nunca reemplaza sin confirmación.
create or replace function public.aplicar_plantilla_proyecto(
    p_proyecto_id uuid,
    p_plantilla_id uuid,
    p_partidas jsonb,
    p_reemplazar boolean default false
)
returns setof public.proyecto_partidas
language plpgsql
security invoker
set search_path = ''
as $$
begin
    -- RLS oculta los proyectos ajenos.
    perform 1 from public.proyectos where id = p_proyecto_id for update;
    if not found then
        raise exception 'Proyecto no encontrado'
            using errcode = 'P0002';
    end if;

    if jsonb_typeof(p_partidas) is distinct from 'array' then
        raise exception 'Las partidas de la plantilla deben ser una lista.'
            using errcode = '22023';
    end if;

    if not p_reemplazar and exists (
        select 1 from public.proyecto_partidas where proyecto_id = p_proyecto_id
    ) then
        raise exception 'El proyecto ya tiene partidas. Confirma si quieres reemplazarlas.'
            using errcode = '55000';
    end if;

    delete from public.proyecto_partidas where proyecto_id = p_proyecto_id;

    insert into public.proyecto_partidas (
        proyecto_id, partida_id, categoria_id, nombre, unidad,
        cantidad, precio_unitario_override, origen, orden, observacion
    )
    select
        p_proyecto_id, r.partida_id, r.categoria_id, r.nombre, r.unidad,
        r.cantidad, null, 'plantilla', r.orden, null
    from jsonb_populate_recordset(null::public.proyecto_partidas, p_partidas) r;

    update public.proyectos
    set plantilla_id = p_plantilla_id
    where id = p_proyecto_id;

    return query
        select * from public.proyecto_partidas
        where proyecto_id = p_proyecto_id
        order by orden;
end;
$$;

-- Crea el proyecto y copia su plantilla en una sola transacción:
-- si falla la copia, tampoco queda el proyecto.
create or replace function public.crear_proyecto_con_plantilla(
    p_proyecto jsonb,
    p_plantilla_id uuid,
    p_partidas jsonb
)
returns public.proyectos
language plpgsql
security invoker
set search_path = ''
as $$
declare
    v_proyecto public.proyectos;
begin
    -- RLS exige usuario_id = auth.uid().
    insert into public.proyectos (
        usuario_id, nombre, comuna, tipo_obra, materialidad,
        superficie_m2, numero_pisos, estandar_terminaciones
    )
