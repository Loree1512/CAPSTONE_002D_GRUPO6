-- Marcar vigente publica (así funciona también el seed de precios). Una vez
-- publicada, la fecha no se cambia ni se borra.
create or replace function public.conservar_fecha_publicacion()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if tg_op = 'UPDATE'
       and old.fecha_publicacion is not null
       and new.fecha_publicacion is distinct from old.fecha_publicacion then
        raise exception 'Una versión publicada no vuelve a ser borrador ni cambia su fecha de publicación.'
            using errcode = '55000';
    end if;

    if new.vigente and new.fecha_publicacion is null then
        new.fecha_publicacion := now();
    end if;
    return new;
end;
$$;

create trigger versiones_precios_conservar_publicacion
    before insert or update on public.versiones_precios
    for each row
    execute function public.conservar_fecha_publicacion();

