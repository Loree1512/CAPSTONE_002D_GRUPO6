-- Los precios están expresados en la unidad de la partida: si alguna vez tuvo
-- precios, la unidad no cambia. Se da de baja y se crea otra partida.
create or replace function public.bloquear_unidad_con_precios()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    if new.unidad is distinct from old.unidad
       and exists (select 1 from public.precios_partida where partida_id = old.id) then
        raise exception 'La partida ya tiene precios en el banco: para usar otra unidad, dala de baja y crea una nueva partida.'
            using errcode = '55000';
    end if;
    return new;
end;
$$;

create trigger partidas_unidad_con_precios
    before update of unidad on public.partidas
    for each row
    execute function public.bloquear_unidad_con_precios();

-- Partidas con precio en al menos una versión (tiene_precios en el banco).
create view public.partidas_con_precios
with (security_invoker = true)
as
select distinct partida_id
from public.precios_partida;

grant select on public.partidas_con_precios to authenticated, service_role;


