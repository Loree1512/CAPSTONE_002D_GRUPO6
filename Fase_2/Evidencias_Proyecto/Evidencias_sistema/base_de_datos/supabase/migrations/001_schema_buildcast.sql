-- 11. RPC del banco (solo service role)

-- Crea una versión borrador, opcionalmente copiando los precios de otra.
create or replace function public.crear_version_precios(
    p_version text,
    p_copiar_de uuid default null
)
returns public.versiones_precios
language plpgsql
set search_path = ''
as $$
declare
    v_nombre text := btrim(p_version);
    v_origen public.versiones_precios;
    v_nueva public.versiones_precios;
begin
    if v_nombre is null or v_nombre = '' then
        raise exception 'El nombre de la versión es obligatorio.'
            using errcode = '22023';
    end if;

    if p_copiar_de is not null then
        select * into v_origen
        from public.versiones_precios
        where id = p_copiar_de;

        if not found then
            raise exception 'La versión de origen no existe.'
                using errcode = 'P0002';
        end if;
    end if;

    -- Nombre duplicado: el unique de version lanza 23505.
    insert into public.versiones_precios (version, trimestre, fuente)
    values (
        v_nombre,
        substring(v_nombre from '^\d{4}-T[1-4]'),
        case when p_copiar_de is not null then 'Copiada de ' || v_origen.version end
    )
    returning * into v_nueva;

    if p_copiar_de is not null then
        insert into public.precios_partida
            (partida_id, version_precio_id, precio_unitario, rendimiento_mo, fuente)
        select partida_id, v_nueva.id, precio_unitario, rendimiento_mo, fuente
        from public.precios_partida
        where version_precio_id = p_copiar_de;
    end if;

    return v_nueva;
end;
$$;

-- Deja una única versión vigente. La primera vez fija fecha_publicacion; volver a
-- marcar vigente una versión histórica no toca su fecha ni su contenido.
create or replace function public.publicar_version_precios(p_version_id uuid)
returns public.versiones_precios
language plpgsql
set search_path = ''
as $$
declare
    v_version public.versiones_precios;
begin
    -- Serializa publicaciones concurrentes; las lecturas no se bloquean.
    lock table public.versiones_precios in share row exclusive mode;

    if not exists (select 1 from public.versiones_precios where id = p_version_id) then
        raise exception 'La versión de precios no existe.'
            using errcode = 'P0002';
    end if;

    -- Primero apagar la vigente: el índice único parcial no admite dos a la vez.
    update public.versiones_precios
    set vigente = false
    where vigente and id <> p_version_id;

    update public.versiones_precios
    set vigente = true,
        fecha_publicacion = coalesce(fecha_publicacion, now())
    where id = p_version_id
    returning * into v_version;

    return v_version;
end;
$$;

-- Crea una partida no base con el siguiente código libre de su categoría.
create or replace function public.crear_partida_banco(
    p_categoria_id integer,
    p_nombre text,
    p_unidad text
)
returns public.partidas
language plpgsql
set search_path = ''
as $$
declare
    v_categoria public.categorias_partida;
    v_siguiente integer;
    v_partida public.partidas;
begin
    if btrim(coalesce(p_nombre, '')) = '' then
        raise exception 'El nombre de la partida es obligatorio.'
            using errcode = '22023';
    end if;

    -- Bloquea la categoría: dos altas simultáneas no calculan el mismo código.
    select * into v_categoria
    from public.categorias_partida
    where id = p_categoria_id and vigente
    for update;

    if not found then
        raise exception 'La categoría no existe.'
            using errcode = 'P0002';
    end if;

    -- Códigos que no terminan en .N se ignoran; una categoría vacía parte en 01.
    select coalesce(max(substring(codigo from '\.(\d+)$')::integer), 0) + 1
    into v_siguiente
    from public.partidas
    where categoria_id = p_categoria_id;

    -- Unidad fuera del catálogo: el check de partidas lanza 23514.
    insert into public.partidas (categoria_id, codigo, nombre, unidad, es_base)
    values (
        p_categoria_id,
        v_categoria.codigo || '.' || lpad(v_siguiente::text, 2, '0'),
        btrim(p_nombre),
        p_unidad,
        false
    )
    returning * into v_partida;

    return v_partida;
end;
$$;

