-- Precios de una versión publicada: ni altas, ni cambios, ni bajas.

create or replace function public.bloquear_precios_version_publicada()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
    v_anterior uuid;
    v_nueva uuid;
begin
    if tg_op <> 'INSERT' then
        v_anterior := old.version_precio_id;
    end if;
    if tg_op <> 'DELETE' then
        v_nueva := new.version_precio_id;
    end if;

    if exists (
        select 1 from public.versiones_precios v
        where v.fecha_publicacion is not null
          and (v.id = v_anterior or v.id = v_nueva)
    ) then
        raise exception 'Una versión publicada no se puede modificar. Crea una nueva versión para cambiar precios.'
            using errcode = '55000';
    end if;

    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end;
$$;

create trigger precios_partida_version_publicada_inmutable
    before insert or update or delete on public.precios_partida
    for each row
    execute function public.bloquear_precios_version_publicada();

alter table public.precios_partida enable row level security;

