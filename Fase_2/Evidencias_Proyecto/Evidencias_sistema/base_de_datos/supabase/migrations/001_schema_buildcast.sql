-- Esquema base de BuildCast.
-- Crea todo lo necesario para levantar el sistema desde cero. Los datos iniciales
-- (catálogo, precios, configuración y plantillas) están en supabase/seeds/.
--
-- Motor de costos: presupuesto por partidas del proyecto (cantidad × precio unitario).
-- Las escrituras de banco, configuración, plantillas y estimaciones las hace el backend
-- con service role tras validar permisos; los proyectos y sus partidas, con el token del
-- usuario y RLS.


-- 1. Utilidades

-- Actualiza fecha_actualizacion en cada UPDATE.
create or replace function public.actualizar_fecha_actualizacion()
returns trigger
language plpgsql
as $$
begin
    new.fecha_actualizacion = now();
    return new;
end;
$$;


