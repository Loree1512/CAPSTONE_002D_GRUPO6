-- 10. Estimaciones

-- Cada cálculo del motor, inmutable. Guarda copia de todo lo usado para que no cambie
-- si después se editan el proyecto, sus partidas, el banco, la plantilla o la configuración.
create table public.estimaciones (
    id uuid primary key default gen_random_uuid(),

    proyecto_id uuid not null
        references public.proyectos(id) on delete cascade,

    usuario_id uuid references auth.users(id) on delete set null,

    -- Versión de precios usada, con copia de su nombre y fuente.
    version_precio_id uuid not null
        references public.versiones_precios(id) on delete restrict,
    version_precio text not null,
    fuente_version_precio text,

    -- Datos del proyecto al momento de estimar.
    comuna text not null,
    tipo_obra text not null,
    materialidad text not null,
    superficie_m2 numeric not null
        check (superficie_m2 > 0),
    numero_pisos integer not null
        check (numero_pisos > 0),
    estandar_terminaciones text not null
        check (estandar_terminaciones in ('economico', 'medio', 'alto')),

    -- Configuración y versión del motor usadas.
    parametros_snapshot jsonb not null,
    version_motor text not null,

    -- Factores de comuna y pisos; valen 1 si no se aplicaron.
    aplicar_factores boolean not null default false,
    factor_comuna numeric not null check (factor_comuna > 0),
    factor_pisos numeric not null check (factor_pisos > 0),
    factor_ajuste numeric not null check (factor_ajuste > 0),

    -- Montos en CLP entero; costo_m2 sin redondear.
    costo_directo_base numeric not null check (costo_directo_base >= 0),
    costo_directo numeric not null check (costo_directo >= 0),
    gastos_generales_pct numeric not null
        constraint estimaciones_gastos_generales_pct_rango_chk check (gastos_generales_pct between 0 and 25),
    gastos_generales numeric not null check (gastos_generales >= 0),
    utilidad_pct numeric not null
        constraint estimaciones_utilidad_pct_rango_chk check (utilidad_pct between 0 and 30),
    utilidad numeric not null check (utilidad >= 0),
    costo_total numeric not null check (costo_total >= 0),
    costo_m2 numeric not null check (costo_m2 >= 0),

    partidas_calculadas integer not null check (partidas_calculadas >= 0),
    partidas_sin_precio integer not null check (partidas_sin_precio >= 0),
    partidas_sin_cantidad integer not null check (partidas_sin_cantidad >= 0),

    -- Huella de las partidas usadas: si cambia, el proyecto queda por recalcular.
    firma_partidas text not null,

    -- false si alguna partida quedó sin cantidad o sin precio.
    completa boolean not null,

    fecha_creacion timestamptz not null default now()
);

-- Historial de un proyecto, más reciente primero.
